/* The name of `code` in the language `display_lang` ("ja" or anything else),
 * or `code` itself when the platform has no name for it. */
static const char *loc_display_name(const struct loc_name *table, size_t n,
                                    const char *code, const char *display_lang)
{
   if (!code || !*code) return "";
   size_t lo = 0, hi = n;
   while (lo < hi) {           /* the tables are sorted by code */
      size_t mid = lo + (hi - lo) / 2;
      int c = strcasecmp(table[mid].code, code);
      if (!c) return (display_lang && !strncasecmp(display_lang, "ja", 2))
                        ? table[mid].ja : table[mid].en;
      if (c < 0) lo = mid + 1; else hi = mid;
   }
   return code;
}
