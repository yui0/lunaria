#!/usr/bin/env python3
"""Generate Gregorian DateFormatSymbols data from ICU using its C API.
Usage: gen-date-symbols.py src/dvm/date_symbols_data.h
ICU is needed only when regenerating the checked-in data, not at runtime.
"""
import ctypes as c
import ctypes.util
import json
import re
import sys

name = ctypes_name = ctypes.util.find_library('icui18n') or ctypes.util.find_library('icucore')
if not name:
    raise SystemExit('ICU i18n library not found')
lib = c.CDLL(name)
match = re.search(r'(?:\.so\.|\.)(\d+)(?:\.dylib)?$', name)
suffix = '_' + match.group(1) if match else ''
def fn(name, restype, args):
    try:
        f = getattr(lib, name)
    except AttributeError:
        f = getattr(lib, name + suffix)
    f.restype, f.argtypes = restype, args
    return f
errptr = c.POINTER(c.c_int)
open_date = fn('udat_open', c.c_void_p, [c.c_int,c.c_int,c.c_char_p,c.c_void_p,c.c_int,c.c_void_p,c.c_int,errptr])
close_date = fn('udat_close', None, [c.c_void_p])
get = fn('udat_getSymbols', c.c_int, [c.c_void_p,c.c_int,c.c_int,c.POINTER(c.c_uint16),c.c_int,errptr])
count = fn('uloc_countAvailable', c.c_int, [])
available = fn('uloc_getAvailable', c.c_char_p, [c.c_int])
locales = sorted({'root'} | {available(i).decode() for i in range(count())})
if len(sys.argv) == 3 and sys.argv[2] == '--standalone':
    rows, index, lookup = [], {}, []
    for locale in locales:
        error = c.c_int(0)
        fmt = open_date(2,2,(locale+'@calendar=gregorian').encode(),None,0,None,0,c.byref(error))
        if not fmt or error.value > 0:
            raise RuntimeError((locale, error.value))
        row = []
        try:
            for month in range(12):
                error = c.c_int(0)
                buf = (c.c_uint16 * 512)()
                n = get(fmt,10,month,buf,len(buf),c.byref(error))
                if error.value > 0 or n >= len(buf):
                    raise RuntimeError((locale,month,error.value,n))
                row.append(bytes(buf)[:2*n].decode('utf-16-le' if sys.byteorder=='little' else 'utf-16-be'))
        finally:
            close_date(fmt)
        row = tuple(row)
        if row not in index:
            index[row] = len(rows)
            rows.append(row)
        lookup.append((locale,index[row]))
    with open(sys.argv[1], 'w', encoding='utf-8') as out:
        out.write('/* Generated by scripts/gen-date-symbols.py --standalone from ICU/CLDR. */\n')
        out.write('static const char *const time_standalone_months[][12]={\n')
        for row in rows:
            out.write(' {'+','.join(json.dumps(s,ensure_ascii=False) for s in row)+'},\n')
        out.write('};\nstatic const struct {const char *locale; unsigned short row;} time_standalone_locales[]={\n')
        for locale, row in lookup:
            out.write(' {'+json.dumps(locale)+','+str(row)+'},\n')
        out.write('};\n')
    print(f'{len(locales)} locales, {len(rows)} standalone month sets')
    sys.exit(0)
rows, index, lookup = [], {}, []
for locale in locales:
    error = c.c_int(0)
    fmt = open_date(2,2,(locale+'@calendar=gregorian').encode(),None,0,None,0,c.byref(error))
    if not fmt or error.value > 0:
        raise RuntimeError((locale, error.value))
    row = []
    try:
        for kind, size in enumerate([2,13,13,8,8,2]):
            for i in range(size):
                # Java's Gregorian month arrays reserve index 12 for UNDECIMBER.
                if kind in (1,2) and i == 12:
                    row.append(''); continue
                error = c.c_int(0)
                buf = (c.c_uint16 * 512)()
                n = get(fmt,kind,i,buf,len(buf),c.byref(error))
                if error.value > 0 or n >= len(buf):
                    raise RuntimeError((locale,kind,i,error.value,n))
                row.append(bytes(buf)[:2*n].decode('utf-16-le' if sys.byteorder=='little' else 'utf-16-be'))
    finally:
        close_date(fmt)
    row = tuple(row)
    if row not in index:
        index[row] = len(rows); rows.append(row)
    lookup.append((locale,index[row]))
# Standard Java DateFormat date styles: FULL, LONG, MEDIUM, SHORT.
pattern = fn('udat_toPattern',c.c_int,[c.c_void_p,c.c_int,c.POINTER(c.c_uint16),c.c_int,errptr])
number_open = fn('unum_open',c.c_void_p,[c.c_int,c.c_void_p,c.c_int,c.c_char_p,c.c_void_p,errptr])
number_symbol = fn('unum_getSymbol',c.c_int,[c.c_void_p,c.c_int,c.POINTER(c.c_uint16),c.c_int,errptr])
number_close = fn('unum_close',None,[c.c_void_p])
patterns,pattern_index,pattern_lookup=[],{},[]
for locale in locales:
    values=[]
    for style in range(4):
        error=c.c_int(0)
        fmt=open_date(-1,style,(locale+'@calendar=gregorian').encode(),None,0,None,0,c.byref(error))
        if not fmt or error.value>0: raise RuntimeError((locale,style,error.value))
        try:
            buf=(c.c_uint16*512)()
            n=pattern(fmt,0,buf,len(buf),c.byref(error))
            if error.value>0 or n>=len(buf): raise RuntimeError((locale,style,error.value,n))
            values.append(bytes(buf)[:2*n].decode('utf-16-le' if sys.byteorder=='little' else 'utf-16-be'))
        finally: close_date(fmt)
    error=c.c_int(0)
    number=number_open(1,None,0,locale.encode(),None,c.byref(error))
    if not number or error.value>0: raise RuntimeError((locale,error.value))
    try:
        buf=(c.c_uint16*8)()
        n=number_symbol(number,4,buf,len(buf),c.byref(error))
        if error.value>0 or n>=len(buf): raise RuntimeError((locale,error.value,n))
        zero=bytes(buf)[:2*n].decode('utf-16-le' if sys.byteorder=='little' else 'utf-16-be')
        if len(zero)!=1: raise RuntimeError((locale,zero))
        values.append(ord(zero))
    finally: number_close(number)
    row=tuple(values)
    if row not in pattern_index:
        pattern_index[row]=len(patterns);patterns.append(row)
    pattern_lookup.append((locale,pattern_index[row]))
quote = lambda s: json.dumps(s,ensure_ascii=False)
with open(sys.argv[1], 'w', encoding='utf-8') as out:
    out.write('/* Generated by scripts/gen-date-symbols.py from ICU/CLDR. Gregorian symbols. */\n#pragma once\n')
    out.write('static const char *const date_symbol_rows[][46] = {\n')
    for row in rows:
        out.write(' {' + ','.join(map(quote,row)) + '},\n')
    out.write('};\nstatic const struct { const char *locale; unsigned short row; } date_symbol_locales[] = {\n')
    for locale,i in lookup:
        out.write(' {'+quote(locale)+','+str(i)+'},\n')
    out.write('};\n')
    out.write('static const struct { const char *styles[4]; unsigned zero; } date_pattern_rows[] = {\n')
    for row in patterns:
        out.write(' {{'+','.join(map(quote,row[:4]))+'},'+str(row[4])+'},\n')
    out.write('};\nstatic const struct { const char *locale; unsigned short row; } date_pattern_locales[] = {\n')
    for locale,i in pattern_lookup:
        out.write(' {'+quote(locale)+','+str(i)+'},\n')
    out.write('};\n')
print(f'{len(locales)} locales, {len(rows)} symbol sets, {len(patterns)} pattern sets')
