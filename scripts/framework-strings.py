#!/usr/bin/env python3
"""Emit the framework's public string IDs and default values from AOSP XML."""
import json
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

source = pathlib.Path(sys.argv[1])
values = {}
for path in sorted((source / 'res/values').glob('*.xml')):
    for entry in ET.parse(path).getroot():
        if entry.tag == 'string':
            text = ' '.join(''.join(entry.itertext()).split())
            if text.startswith('"') and text.endswith('"'):
                text = text[1:-1]
            text = re.sub(r'\\([\\\'"nt])', lambda m: {'n':'\n','t':'\t'}.get(m[1],m[1]), text)
            values[entry.get('name')] = text
def resolve(name, seen=()):
    if name in seen:
        raise ValueError('cyclic framework string reference: ' + name)
    text = values[name]
    if text.startswith('@string/'):
        return resolve(text[len('@string/'):], (*seen, name))
    return text

print('''/* Generated by scripts/framework-strings.py from AOSP framework-res.
 * Copyright 2006 The Android Open Source Project
 * Licensed under the Apache License, Version 2.0.
 * https://www.apache.org/licenses/LICENSE-2.0
 * Default-locale public strings; package 0x01 belongs to Android.
 */
#ifndef LUNA_FRAMEWORK_STRINGS_H
#define LUNA_FRAMEWORK_STRINGS_H
#include <stdint.h>
#include <stddef.h>
#include <string.h>
static const struct { uint32_t id; const char *name, *value; } luna_framework_strings[] = {''')
for entry in ET.parse(source / 'res/values/public-final.xml').getroot():
    if entry.tag == 'public' and entry.get('type') == 'string':
        name = entry.get('name')
        if name in values:
            print('    {%su, %s, %s},' % (entry.get('id'), json.dumps(name), json.dumps(resolve(name),ensure_ascii=False)))
print('''};
static inline uint32_t luna_framework_string_id(const char *name)
{
    for (size_t i=0; i<sizeof luna_framework_strings/sizeof *luna_framework_strings; ++i)
        if (name && !strcmp(name,luna_framework_strings[i].name)) return luna_framework_strings[i].id;
    return 0;
}
static inline const char *luna_framework_string_value(uint32_t id)
{
    for (size_t i=0; i<sizeof luna_framework_strings/sizeof *luna_framework_strings; ++i)
        if (id==luna_framework_strings[i].id) return luna_framework_strings[i].value;
    return NULL;
}
#endif''')
