#!/usr/bin/env python3
"""Compile the guest libc C implementation into relocatable guest stub words."""
import argparse
import pathlib
import struct
import subprocess
import tempfile

root = pathlib.Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true', help='verify the checked-in code without writing')
options = parser.parse_args()


def text_section(path):
    data = path.read_bytes()
    wide = data[4] == 2
    assert data[:4] == b'\x7fELF' and data[5] == 1
    shoff = struct.unpack_from('<Q' if wide else '<I', data, 40 if wide else 32)[0]
    size, count, strings = struct.unpack_from('<HHH', data, 58 if wide else 46)

    def section(index):
        at = shoff + size * index
        name, kind = struct.unpack_from('<II', data, at)
        offset, length = struct.unpack_from('<QQ' if wide else '<II', data,
                                             at + (24 if wide else 16))
        return name, kind, data[offset:offset + length]

    names = section(strings)[2]
    code = None
    for i in range(count):
        name, kind, contents = section(i)
        name = names[name:].split(b'\0', 1)[0]
        if name in (b'.rel.text', b'.rela.text') and contents:
            raise ValueError('guest stub has unresolved text relocations')
        if name == b'.text':
            code = contents
    assert code and len(code) % 4 == 0 and len(code) <= 256
    return struct.unpack('<%dI' % (len(code) // 4), code)


output = ['/* SPDX-License-Identifier: MPL-2.0 */',
          '/* Generated by scripts/gen-guest-init.py from the guest C implementations. */']
with tempfile.TemporaryDirectory(prefix='lunaria-once-') as directory:
    for abi, target, flags in [(32, 'armv7a-linux-gnueabihf', ['-marm', '-mfloat-abi=softfp']),
                               (64, 'aarch64-linux-gnu', [])]:
        for name, operation in [('pthread_once', 0), ('cxa_guard_acquire', 1),
                                      ('cxa_guard_release', 2), ('cxa_guard_abort', 3)]:
            obj = pathlib.Path(directory) / ('%s%d.o' % (name, abi))
            defines = ['-DLUNARIA_GUEST_INIT', '-DLUNA_GUARD_OPERATION=%d' % operation]
            subprocess.run(['clang', '-target', target, *flags, *defines, '-std=c11', '-O2',
                            '-ffreestanding', '-nostdlibinc', '-fno-stack-protector',
                            '-fno-unwind-tables', '-fno-asynchronous-unwind-tables',
                            '-c', str(root / 'src/lib/guest.c'), '-o', str(obj)], check=True)
            words = text_section(obj)
            output.append('static const uint32_t %s_code%d[] = {' % (name, abi))
            for i in range(0, len(words), 4):
                output.append('    ' + ', '.join('0x%08xu' % w for w in words[i:i + 4]) + ',')
            output.append('};')
            print('%s ARM%d: %d bytes' % (name, abi, len(words) * 4))
generated = '\n'.join(output) + '\n'
bridge = root / 'src/arm_exec.cpp'
text = bridge.read_text()
begin = '/* BEGIN GENERATED GUEST INITIALIZERS */\n'
end = '/* END GENERATED GUEST INITIALIZERS */'
start = text.index(begin) + len(begin)
stop = text.index(end, start)
if options.check:
    if text[start:stop] != generated:
        raise SystemExit('arm_exec.cpp guest initializers are stale; run scripts/gen-guest-init.py')
else:
    bridge.write_text(text[:start] + generated + text[stop:])
