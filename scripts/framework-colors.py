#!/usr/bin/env python3
"""Emit literal public Android colors from a local AOSP core/res directory.

State-list XML resources are not collapsed to a constant. Resolve aliases only
when they terminate at a literal color in the default configuration.
"""
import pathlib
import sys
import xml.etree.ElementTree as ET

source = pathlib.Path(sys.argv[1]) / 'res/values'
values = {}
for path in sorted(source.glob('*.xml')):
    for entry in ET.parse(path).getroot():
        if entry.tag == 'color' and entry.text:
            values[entry.get('name')] = entry.text.strip()

def resolve(name, seen=()):
    if name in seen:
        raise ValueError('cyclic framework color reference: ' + name)
    value = values.get(name, '')
    if value.startswith('@color/'):
        return resolve(value[7:], (*seen, name))
    if not value.startswith('#'):
        return None
    digits = value[1:]
    if len(digits) in (3, 4):
        digits = ''.join(ch * 2 for ch in digits)
    if len(digits) == 6:
        digits = 'ff' + digits
    if len(digits) != 8:
        raise ValueError('invalid color: ' + value)
    return int(digits, 16)

print('''/* Generated by scripts/framework-colors.py from AOSP Android 12 framework-res.
 * Copyright The Android Open Source Project, Apache License 2.0.
 * https://www.apache.org/licenses/LICENSE-2.0
 * Default-configuration literal public colors; state lists remain resources.
 */
#ifndef LUNA_FRAMEWORK_COLORS_H
#define LUNA_FRAMEWORK_COLORS_H
#include <stdint.h>
#include <stddef.h>
#include <string.h>
#include <stdbool.h>
static const struct { uint32_t id, value; const char *name; } luna_framework_colors[]={''')
public = source / 'public-final.xml'
if not public.exists():
    public = source / 'public.xml'
for entry in ET.parse(public).getroot():
    if entry.tag == 'public' and entry.get('type') == 'color':
        name = entry.get('name')
        value = resolve(name)
        if value is not None:
            print(' { %su, 0x%08xu, "%s" },' % (entry.get('id'), value, name))
print('''};
static inline bool luna_framework_color_value(uint32_t id,int32_t *out)
{
 for(size_t i=0;i<sizeof luna_framework_colors/sizeof *luna_framework_colors;++i)
  if(luna_framework_colors[i].id==id) {*out=(int32_t)luna_framework_colors[i].value;return true;}
 return false;
}
static inline uint32_t luna_framework_color_id(const char *name)
{
 for(size_t i=0;i<sizeof luna_framework_colors/sizeof *luna_framework_colors;++i)
  if(name && !strcmp(name,luna_framework_colors[i].name)) return luna_framework_colors[i].id;
 return 0;
}
static inline const char *luna_framework_color_name(uint32_t id)
{
 for(size_t i=0;i<sizeof luna_framework_colors/sizeof *luna_framework_colors;++i)
  if(luna_framework_colors[i].id==id) return luna_framework_colors[i].name;
 return NULL;
}
#endif''')
