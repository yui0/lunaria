#!/usr/bin/env python3
"""Generate src/unicode/block_data.h from a Unicode Blocks.txt.
Usage: python3 scripts/generate-unicode-blocks.py /usr/share/perl5/unicore/Blocks.txt > src/unicode/block_data.h
UnicodeSet's [:Block=Name:] reads it; names are matched without case, spaces, '_' and '-'.
"""
import sys
rows = []
for line in open(sys.argv[1], encoding="utf-8"):
    line = line.split("#")[0].strip()
    if not line:
        continue
    rng, name = [s.strip() for s in line.split(";")]
    a, b = rng.split("..")
    rows.append((int(a, 16), int(b, 16), name))
print("/* Generated by scripts/generate-unicode-blocks.py from Unicode Blocks.txt. */")
print("static const struct uc_block { uint32_t first, last; const char *name; } uc_blocks[] = {")
for a, b, n in rows:
    print('{0x%x,0x%x,"%s"},' % (a, b, n))
print("};")
