#!/usr/bin/env python3
"""Generate Gregorian time/date-time patterns from ICU; no runtime ICU needed.

Usage: gen-date-time-patterns.py src/dvm/date_time_patterns_data.h
"""
import ctypes as c
import ctypes.util
import json
import re
import sys

name = ctypes.util.find_library('icui18n') or ctypes.util.find_library('icucore')
if not name:
    raise SystemExit('ICU library not found')
lib = c.CDLL(name)
match = re.search(r'(?:\.so\.|\.)(\d+)(?:\.dylib)?$', name)
suffix = '_' + match.group(1) if match else ''


def fn(name, result, args):
    try:
        f = getattr(lib, name)
    except AttributeError:
        f = getattr(lib, name + suffix)
    f.restype, f.argtypes = result, args
    return f


errptr = c.POINTER(c.c_int)
open_date = fn('udat_open', c.c_void_p,
               [c.c_int, c.c_int, c.c_char_p, c.c_void_p, c.c_int,
                c.c_void_p, c.c_int, errptr])
close_date = fn('udat_close', None, [c.c_void_p])
pattern = fn('udat_toPattern', c.c_int,
             [c.c_void_p, c.c_int, c.POINTER(c.c_uint16), c.c_int, errptr])
count = fn('uloc_countAvailable', c.c_int, [])
available = fn('uloc_getAvailable', c.c_char_p, [c.c_int])
version = fn('u_getVersion', None, [c.POINTER(c.c_uint8)])
v = (c.c_uint8 * 4)()
version(v)
locales = sorted({'root'} | {available(i).decode() for i in range(count())})
rows, indices, lookup = [], {}, []
for locale in locales:
    values = []
    # Time-only FULL..SHORT, then all dateStyle/timeStyle combinations.
    for date_style, time_style in ([(-1, t) for t in range(4)] +
                                 [(d, t) for d in range(4) for t in range(4)]):
        error = c.c_int(0)
        fmt = open_date(time_style, date_style,
                        (locale + '@calendar=gregorian').encode(),
                        None, 0, None, 0, c.byref(error))
        if not fmt or error.value > 0:
            raise RuntimeError((locale, date_style, time_style, error.value))
        try:
            buf = (c.c_uint16 * 1024)()
            n = pattern(fmt, 0, buf, len(buf), c.byref(error))
            if error.value > 0 or n >= len(buf):
                raise RuntimeError((locale, error.value, n))
            values.append(bytes(buf)[:2*n].decode(
                'utf-16-le' if sys.byteorder == 'little' else 'utf-16-be'))
        finally:
            close_date(fmt)
    row = tuple(values)
    if row not in indices:
        indices[row] = len(rows)
        rows.append(row)
    lookup.append((locale, indices[row]))

quote = lambda s: json.dumps(s, ensure_ascii=False)
with open(sys.argv[1], 'w', encoding='utf-8') as out:
    out.write('/* Generated by scripts/gen-date-time-patterns.py from ICU ' +
              '.'.join(map(str, v)) + '/CLDR. Gregorian patterns. */\n#pragma once\n')
    out.write('static const char *const date_time_pattern_rows[][20] = {\n')
    for row in rows:
        out.write(' {' + ','.join(map(quote, row)) + '},\n')
    out.write('};\nstatic const struct { const char *locale; unsigned short row; } date_time_pattern_locales[] = {\n')
    for locale, index in lookup:
        out.write(' {' + quote(locale) + ',' + str(index) + '},\n')
    out.write('};\n')
print(f'{len(locales)} locales, {len(rows)} date/time pattern sets')
