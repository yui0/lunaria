#!/usr/bin/env python3
"""Extract Android's legacy strftime resource patterns, with a download cache.

Usage: gen-time-format-resources.py CACHE OUTPUT
Source: AOSP frameworks/base, android-12.0.0_r1 (Apache-2.0).
No network or Android resource dependency is needed at runtime.
"""
import base64
from concurrent.futures import ThreadPoolExecutor
import json
from pathlib import Path
import re
import sys
import urllib.request
import urllib.error
import xml.etree.ElementTree as ET

cache, output = Path(sys.argv[1]), Path(sys.argv[2])
cache.mkdir(parents=True, exist_ok=True)
base = 'https://android.googlesource.com/platform/frameworks/base/+/android-12.0.0_r1/core/res/res/'

def fetch(path, name):
    target = cache / name
    if not target.exists():
        try:
            with urllib.request.urlopen(base + path, timeout=60) as response:
                data = response.read()
        except urllib.error.HTTPError as error:
            if error.code != 429 or not path.endswith('?format=TEXT'):
                raise
            mirror = 'https://raw.githubusercontent.com/aosp-mirror/platform_frameworks_base/android-12.0.0_r1/core/res/res/'
            with urllib.request.urlopen(mirror + path.removesuffix('?format=TEXT'), timeout=60) as response:
                data = base64.b64encode(response.read())
        target.write_bytes(data)
    return target.read_bytes()

tree = json.loads(fetch('?format=JSON', 'tree.json')[4:])
directories = [e['name'] for e in tree['entries'] if re.fullmatch(
    r'values(?:-[a-z]{2,3}(?:-r[A-Z]{2})?|-b\+[a-zA-Z+]+)?', e['name'])]
keys = ('time_of_day', 'month_day_year', 'date_and_time')

def read(directory):
    try:
        data = base64.b64decode(fetch(directory + '/donottranslate-cldr.xml?format=TEXT', directory + '-cldr.b64'))
    except urllib.error.HTTPError as error:
        if error.code == 404:
            return directory[7:].replace('-r', '_').replace('b+', '').replace('+', '_') or 'root', {}
        raise
    root = ET.fromstring(data)
    found = {}
    for element in root.findall('string'):
        if element.get('name') in keys:
            value = ''.join(element.itertext()).strip()
            if value.startswith('"') and value.endswith('"'):
                value = value[1:-1]
            value = value.replace("\\'", "'").replace('\\"', '"').replace('\\n', '\n').replace('\\t', '\t')
            found[element.get('name')] = value
    locale = directory[7:].replace('-r', '_').replace('b+', '').replace('+', '_') or 'root'
    return locale, found

with ThreadPoolExecutor(max_workers=6) as pool:
    entries = dict(pool.map(read, directories))
assert all(key in entries['root'] for key in keys)
with output.open('w') as stream:
    stream.write('/* Generated by scripts/gen-time-format-resources.py.\n'
                 ' * AOSP frameworks/base android-12.0.0_r1 resource data, Apache-2.0.\n'
                 ' * https://www.apache.org/licenses/LICENSE-2.0\n */\n')
    stream.write('static const struct { const char *locale, *patterns[3]; } android_time_patterns[]={\n')
    for locale, fields in sorted(entries.items()):
        if fields:
            values = [json.dumps(fields[key], ensure_ascii=False) if key in fields else 'NULL' for key in keys]
            stream.write(' {' + json.dumps(locale) + ',{' + ','.join(values) + '}},\n')
    stream.write('};\n')
print(f'{len(entries)} resource locales, {sum(bool(v) for v in entries.values())} pattern overrides')
