#!/usr/bin/env python3
"""Generate C currency metadata from ICU. ICU is only a generation dependency."""
import ctypes as c
import ctypes.util
import json
import re
import sys

name = ctypes.util.find_library('icui18n')
lib = c.CDLL(name)
match = re.search(r'(?:\.so\.|\.)(\d+)(?:\.dylib)?$', name)
suffix = '_' + match[1] if match else ''
def fn(name, result, args):
    try:
        f = getattr(lib, name)
    except AttributeError:
        f = getattr(lib, name + suffix)
    f.restype, f.argtypes = result, args
    return f
errptr = c.POINTER(c.c_int)
uchar = c.POINTER(c.c_uint16)
open_codes = fn('ucurr_openISOCurrencies', c.c_void_p, [c.c_int, errptr])
next_code = fn('uenum_next', c.c_char_p, [c.c_void_p, c.POINTER(c.c_int), errptr])
close_codes = fn('uenum_close', None, [c.c_void_p])
digits = fn('ucurr_getDefaultFractionDigits', c.c_int, [uchar, errptr])
numeric = fn('ucurr_getNumericCode', c.c_int, [uchar])
countries = fn('uloc_getISOCountries', c.POINTER(c.c_char_p), [])
currency = fn('ucurr_forLocale', c.c_int, [c.c_char_p, uchar, c.c_int, errptr])
error = c.c_int(0)
enum = open_codes(0x7fffffff, c.byref(error))
codes = {}
try:
    while True:
        code = next_code(enum, None, c.byref(error))
        if not code:
            break
        code = code.decode()
        units = (c.c_uint16 * 4)(*map(ord, code), 0)
        fraction = digits(units, c.byref(error))
        codes[code] = (fraction, numeric(units))
finally:
    close_codes(enum)
regions = []
iso = countries()
i = 0
while iso[i]:
    region = iso[i].decode()
    error = c.c_int(0)
    buf = (c.c_uint16 * 4)()
    n = currency(('und_' + region).encode(), buf, 4, c.byref(error))
    code = ''.join(chr(buf[j]) for j in range(n)) if error.value <= 0 else ''
    if code == 'XXX': code = ''
    regions.append((region, code))
    i += 1
lines = ['/* Generated by scripts/gen-currency-data.py from ICU. */',
         'static const struct currency_data { char code[4]; int digits, numeric; } currency_data[] = {']
for code, (fraction, number) in sorted(codes.items()):
    lines.append('   {%s, %d, %d},' % (json.dumps(code), fraction, number))
lines += ['};', 'static const struct currency_region { char country[3], code[4]; } currency_regions[] = {']
for region, code in sorted(regions):
    assert not code or code in codes, (region, code)
    lines.append('   {%s, %s},' % (json.dumps(region), json.dumps(code)))
lines += ['};', '']
open(sys.argv[1], 'w').write('\n'.join(lines))
