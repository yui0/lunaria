#!/usr/bin/env python3
"""Independent RFC 7292 appendix B reference vectors, not the runtime KDF.

OpenSSL's command line only encrypts the resulting bytes; hashlib implements
all derivation here. Regenerate: python3 scripts/gen-pbe-test-vectors.py >
test/pbe_vectors.h
"""
import hashlib
import subprocess


def derive(password, salt, iterations, length, diversifier, digest):
    u = hashlib.new(digest).digest_size
    v = hashlib.new(digest).block_size
    encoded = password.encode('utf-16-be', 'surrogatepass') + b'\0\0' if password else b''
    def repeated(data):
        return (data * ((v * ((len(data) + v - 1) // v) + len(data) - 1) // len(data)))[:v * ((len(data) + v - 1) // v)] if data else b''
    block = repeated(salt) + repeated(encoded)
    output = b''
    while len(output) < length:
        a = bytes([diversifier]) * v + block
        for _ in range(iterations):
            a = hashlib.new(digest, a).digest()
        output += a
        b = (a * ((v + u - 1) // u))[:v]
        increment = int.from_bytes(b, 'big') + 1
        modulus = 1 << (v * 8)
        block = b''.join(((int.from_bytes(block[i:i+v], 'big') + increment) % modulus).to_bytes(v, 'big') for i in range(0, len(block), v))
    return output[:length]


print('/* Generated by scripts/gen-pbe-test-vectors.py: independent RFC 7292 KDF. */')
print('static const struct { const char *algorithm; int password; const char *key, *iv, *cipher; } pbe_vectors[] = {')
for digest, label in [('sha1', 'SHA'), ('sha256', 'SHA256')]:
    for bits in [128, 192, 256]:
        for index, password in enumerate(['password', '密碼\0😀', '']):
            salt = bytes.fromhex('1234567890abcdef')
            key = derive(password, salt, 37, bits // 8, 1, digest)
            iv = derive(password, salt, 37, 16, 2, digest)
            cipher = subprocess.run(['openssl', 'enc', f'-aes-{bits}-cbc', '-K', key.hex(), '-iv', iv.hex()], input=b'Android PBE ciphertext\0with padding', check=True, capture_output=True).stdout
            print(f'   {{"PBEWITH{label}AND{bits}BITAES-CBC-BC",{index},"{key.hex()}","{iv.hex()}","{cipher.hex()}"}},')
print('};')
